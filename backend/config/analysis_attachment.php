<?php

/*
|--------------------------------------------------------------------------
| 依頼AD-1(2026-08-27): 診断への既存資料アップロード
|--------------------------------------------------------------------------
| 商談相手ごとに用意された既存資料(フォーマット未確定)を、管理画面から
| 診断(Analysis)1件につき1件アップロードできるようにする機能の設定。
| 実体ファイルはconfig('analysis.storage_disk')('analysis'ディスク、
| /var/analysis-storage)の専用ディレクトリ(App\Services\Admin\
| AnalysisAttachmentService::storagePath()参照)に保存する ―― 巡回結果の
| 保存領域(analyses/{id}/websites/{id}/...)とは物理的に別のディレクトリ。
*/

return [

    /*
    |--------------------------------------------------------------------------
    | 許可する拡張子
    |--------------------------------------------------------------------------
    | 小文字・カンマ区切り。AD-2で合体を検討する対象(PPTX/PDF/DOCX)に絞る ――
    | フォーマットが確定していない段階で対象を広げすぎない(依頼者指定の
    | 前提)。拡張子だけでなく、実際の中身(マジックバイト)もこの拡張子ごとに
    | 許可されたMIMEタイプと一致するかを検証する
    | (App\Services\Admin\AnalysisAttachmentService::ALLOWED_MIME_TYPES_BY_EXTENSION参照)。
    */
    'allowed_extensions' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('ANALYSIS_ATTACHMENT_ALLOWED_EXTENSIONS', 'pdf,pptx,docx')),
    ))),

    /*
    |--------------------------------------------------------------------------
    | 1ファイルあたりの上限バイト数
    |--------------------------------------------------------------------------
    */
    'max_file_size_bytes' => (int) env('ANALYSIS_ATTACHMENT_MAX_FILE_SIZE_BYTES', 20 * 1024 * 1024), // 20MB

    /*
    |--------------------------------------------------------------------------
    | この機能全体(全診断合計)が/var/analysis-storage上で使ってよい上限
    |--------------------------------------------------------------------------
    | ディスクは9.8GBで、巡回結果(analyses/配下)と共用のため、この機能だけで
    | ディスクを圧迫しないよう上限を設ける(依頼者指定)。アップロード時に
    | 既存の合計サイズ(DBのsize_bytes列の合計、実測のためディスクI/Oは
    | 発生しない)+新規ファイルのサイズがこの値を超える場合は拒否する。
    */
    'total_storage_limit_bytes' => (int) env('ANALYSIS_ATTACHMENT_TOTAL_STORAGE_LIMIT_BYTES', 2 * 1024 * 1024 * 1024), // 2GB

];
